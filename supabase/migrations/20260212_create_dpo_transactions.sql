-- Enable UUID extension if not already enabled
create extension if not exists "uuid-ossp";

create table public.dpo_transactions (
  id uuid default gen_random_uuid() primary key,
  trans_token text unique not null,      -- DPO Transaction Token
  trans_ref text,                        -- DPO Transaction Reference (generated by DPO)
  
  -- Project Specific References
  user_id uuid references auth.users(id), -- Link to auth.users (nullable for guest checkout)
  ref_id text,                           -- Your Order ID, Booking ID, etc.
  ref_type text,                         -- 'order', 'booking', 'subscription'
  metadata jsonb default '{}'::jsonb,    -- Any extra context (plan_name, items, etc.)
  
  -- Payment Details
  amount decimal(10, 2) not null,
  currency text not null default 'USD',
  status text default 'created',         -- created, paid, failed, cancelled, refunded
  
  -- Audit
  created_at timestamp with time zone default timezone('utc'::text, now()),
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- Index for fast lookups
create index idx_dpo_trans_token on public.dpo_transactions(trans_token);
create index idx_dpo_ref_id on public.dpo_transactions(ref_id);

-- Enable RLS
alter table public.dpo_transactions enable row level security;

-- Policies
create policy "Users can view their own transactions"
  on public.dpo_transactions
  for select
  using (auth.uid() = user_id);

create policy "Service role can manage all transactions"
  on public.dpo_transactions
  using (true)
  with check (true);
